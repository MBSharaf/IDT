// Builds perf/idt-load-test.jmx from perf/pages.json.  Usage: node perf/build-jmx.mjs
// Each virtual user makes one visit like a first-time visitor:
//   Home -> think -> Products -> think -> Product (ZDM-E5) -> think -> Contact
// and downloads every same-origin file the browser would (HTML, CSS, JS modules, JSON, images).
// An HTTP Cache Manager plays the browser cache, so files already downloaded are revalidated, not refetched.
// Settings are JMeter properties, e.g.  -Jhost=www.example.com -Jprotocol=https -Jport=443 -Jusers=5000 -Jrampup=10
import fs from 'node:fs';

const pages = JSON.parse(fs.readFileSync(new URL('./pages.json', import.meta.url), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const prop = (k, v, type = 'stringProp') => `<${type} name="${k}">${esc(v)}</${type}>`;

const sampler = (url, name) => {
  const [p, q] = url.split('?');
  const args = q ? q.split('&').map((kv) => {
    const [k, v] = kv.split('=');
    return `<elementProp name="${k}" elementType="HTTPArgument">${prop('Argument.name', k)}${prop('Argument.value', v)}${prop('Argument.metadata', '=')}<boolProp name="HTTPArgument.always_encode">false</boolProp><boolProp name="HTTPArgument.use_equals">true</boolProp></elementProp>`;
  }).join('') : '';
  return `<HTTPSamplerProxy guiclass="HttpTestSampleGui" testclass="HTTPSamplerProxy" testname="${esc(name)}">
  <elementProp name="HTTPsampler.Arguments" elementType="Arguments"><collectionProp name="Arguments.arguments">${args}</collectionProp></elementProp>
  ${prop('HTTPSampler.path', p)}${prop('HTTPSampler.method', 'GET')}
  <boolProp name="HTTPSampler.follow_redirects">true</boolProp><boolProp name="HTTPSampler.use_keepalive">true</boolProp>
</HTTPSamplerProxy><hashTree/>`;
};

const PAGE_TITLES = { home: '01 Home', products: '02 Products', product: '03 Product ZDM-E5', contact: '04 Contact' };
const think = (n) => `<TestAction guiclass="TestActionGui" testclass="TestAction" testname="Think ${n}">
  <intProp name="ActionProcessor.action">1</intProp><intProp name="ActionProcessor.target">0</intProp>
  ${prop('ActionProcessor.duration', '${__Random(${__P(thinkmin,3000)},${__P(thinkmax,6000)})}')}
</TestAction><hashTree/>`;

const journey = Object.entries(PAGE_TITLES).map(([key, title], i) => {
  const reqs = pages[key].map((u, j) => sampler(u, `${title} | ${j === 0 ? 'HTML ' : ''}${u}`)).join('\n');
  const tc = `<TransactionController guiclass="TransactionControllerGui" testclass="TransactionController" testname="${esc(title)} (page)">
  <boolProp name="TransactionController.includeTimers">false</boolProp><boolProp name="TransactionController.parent">false</boolProp>
</TransactionController><hashTree>
${reqs}
</hashTree>`;
  return (i ? think(i) : '') + tc;
}).join('\n');

const jmx = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by perf/build-jmx.mjs from perf/pages.json. Edit those, not this file. -->
<jmeterTestPlan version="1.2" properties="5.0" jmeter="5.6.3">
<hashTree>
<TestPlan guiclass="TestPlanGui" testclass="TestPlan" testname="IDT website - first-visit load test">
  ${prop('TestPlan.comments', 'Run headless: jmeter -n -t perf/idt-load-test.jmx -Jhost=... -Jusers=5000 -Jrampup=10 -l results.jtl -e -o report/')}
  <boolProp name="TestPlan.functional_mode">false</boolProp><boolProp name="TestPlan.serialize_threadgroups">false</boolProp>
  <elementProp name="TestPlan.user_defined_variables" elementType="Arguments"><collectionProp name="Arguments.arguments"/></elementProp>
</TestPlan>
<hashTree>
  <ConfigTestElement guiclass="HttpDefaultsGui" testclass="ConfigTestElement" testname="Target site">
    <elementProp name="HTTPsampler.Arguments" elementType="Arguments"><collectionProp name="Arguments.arguments"/></elementProp>
    ${prop('HTTPSampler.domain', '${__P(host,localhost)}')}${prop('HTTPSampler.port', '${__P(port,8080)}')}${prop('HTTPSampler.protocol', '${__P(protocol,http)}')}
    ${prop('HTTPSampler.implementation', 'HttpClient4')}${prop('HTTPSampler.connect_timeout', '${__P(connecttimeout,10000)}')}${prop('HTTPSampler.response_timeout', '${__P(responsetimeout,30000)}')}
  </ConfigTestElement><hashTree/>
  <HeaderManager guiclass="HeaderPanel" testclass="HeaderManager" testname="Browser headers">
    <collectionProp name="HeaderManager.headers">
      <elementProp name="" elementType="Header">${prop('Header.name', 'User-Agent')}${prop('Header.value', 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36 IDT-LoadTest')}</elementProp>
      <elementProp name="" elementType="Header">${prop('Header.name', 'Accept-Encoding')}${prop('Header.value', 'gzip, deflate')}</elementProp>
      <elementProp name="" elementType="Header">${prop('Header.name', 'Accept-Language')}${prop('Header.value', 'ar-EG,ar;q=0.9,en;q=0.8')}</elementProp>
    </collectionProp>
  </HeaderManager><hashTree/>
  <CacheManager guiclass="CacheManagerGui" testclass="CacheManager" testname="Browser cache">
    <boolProp name="clearEachIteration">true</boolProp><boolProp name="useExpires">true</boolProp>
  </CacheManager><hashTree/>
  <CookieManager guiclass="CookiePanel" testclass="CookieManager" testname="Cookies">
    <collectionProp name="CookieManager.cookies"/><boolProp name="CookieManager.clearEachIteration">true</boolProp>
  </CookieManager><hashTree/>
  <ThreadGroup guiclass="ThreadGroupGui" testclass="ThreadGroup" testname="Visitors">
    ${prop('ThreadGroup.on_sample_error', 'continue')}
    <elementProp name="ThreadGroup.main_controller" elementType="LoopController" guiclass="LoopControlPanel" testclass="LoopController">
      <boolProp name="LoopController.continue_forever">false</boolProp>${prop('LoopController.loops', '${__P(loops,1)}')}
    </elementProp>
    ${prop('ThreadGroup.num_threads', '${__P(users,10)}')}${prop('ThreadGroup.ramp_time', '${__P(rampup,10)}')}
    <boolProp name="ThreadGroup.same_user_on_next_iteration">false</boolProp><boolProp name="ThreadGroup.scheduler">false</boolProp>
  </ThreadGroup>
  <hashTree>
${journey}
  </hashTree>
</hashTree>
</hashTree>
</jmeterTestPlan>
`;
fs.writeFileSync(new URL('./idt-load-test.jmx', import.meta.url), jmx);
console.log('perf/idt-load-test.jmx:', Object.values(PAGE_TITLES).length, 'pages,', Object.keys(PAGE_TITLES).reduce((n, k) => n + pages[k].length, 0), 'requests per visit');
